#!/usr/bin/env python3
"""Generate figures/anim/anim-slo-frontier.svg from data/h100/*.points.json (stdlib only).

The animation shows the H100 prompt-heavy throughput-vs-interactivity frontier twice: first TTFT-blind, then with
every point whose TTFT p90 exceeds 2 s turned hollow and the frontier rebuilt from the remaining points.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SERIES = [("agg DP4", "agg-dp4", "#2a78d6", "#5a9be6", "circle", None),
          ("agg 4x TP1", "agg-4x-tp1", "#eb6834", "#f08a5d", "square", None),
          ("P/D 2P(TP1):1D(TP2), block 64", "pd-2p1d-dtp2-bs64-run2", "#008300", "#3fb950", "diamond", "pd-2p1d-dtp2-bs64-run1")]
X0, X1, XMAX = 92, 632, 130.0
Y0, Y1, YMAX = 468, 118, 1500.0
FLOOR = 35
T = 15  # seconds per loop


def X(v):
    return X0 + v / XMAX * (X1 - X0)


def Y(v):
    return Y0 - v / YMAX * (Y0 - Y1)


def load():
    pts = []
    for label, cfg, col, dcol, shape, extra16 in SERIES:
        ps = [p for p in json.load(open(ROOT / "data/h100" / f"{cfg}.points.json")) if p["shape"] == "prompt-heavy"]
        if extra16:  # the replicated layout's c16 point exists only in run 1
            ps += [p for p in json.load(open(ROOT / "data/h100" / f"{extra16}.points.json")) if p["shape"] == "prompt-heavy" and p["c"] == 16]
        for p in sorted(ps, key=lambda p: p["c"]):
            pts.append(dict(label=label, col=col, dcol=dcol, shape=shape, c=p["c"], x=p["tok_s_user_p90"], y=p["out_tok_s_gpu"],
                            ttft90=p["ttft_p90_ms"], slo=p["slo_ok"], ok=p["ttft_p90_ms"] <= 2000))
    return pts


def staircase(pts):
    xs = sorted({p["x"] for p in pts}, reverse=True)
    best = lambda x: max(p["y"] for p in pts if p["x"] >= x)
    steps, prev = [], None
    for x in sorted(xs):
        v = best(x)
        if v != prev:
            steps.append((x, v))
            prev = v
    # path from x=0 at best(0) stepping down at each x where the best changes
    d, cur = f"M{X(0):.1f},{Y(best(0)):.1f}", best(0)
    for x in sorted(xs):
        if x <= 0:
            continue
        nxt = max((p["y"] for p in pts if p["x"] > x), default=None)
        if nxt is None:
            d += f" H{X(x):.1f}"
            break
        if nxt != cur:
            d += f" H{X(x):.1f} V{Y(nxt):.1f}"
            cur = nxt
    return d, best(FLOOR)


def marker(p, i):
    x, y = X(p["x"]), Y(p["y"])
    cls = f"pt s{SERIES.index(next(s for s in SERIES if s[0] == p['label']))}" + ("" if p["ok"] else " bad")
    anim = "" if p["ok"] else f' style="animation: hollow{i} {T}s linear infinite;"'
    if p["shape"] == "circle":
        return f'<circle class="{cls}" cx="{x:.1f}" cy="{y:.1f}" r="7"{anim}/>'
    if p["shape"] == "square":
        return f'<rect class="{cls}" x="{x - 6.5:.1f}" y="{y - 6.5:.1f}" width="13" height="13"{anim}/>'
    return f'<path class="{cls}" d="M{x:.1f},{y - 8.5:.1f} L{x + 8.5:.1f},{y:.1f} L{x:.1f},{y + 8.5:.1f} L{x - 8.5:.1f},{y:.1f} Z"{anim}/>'


def main():
    pts = load()
    blind_d, blind = staircase(pts)
    slo_pts = [p for p in pts if p["ok"]]
    slo_d, slo = staircase(slo_pts)
    over = blind / slo - 1
    pb = max((p for p in pts if p["x"] >= FLOOR), key=lambda p: p["y"])
    ps = max((p for p in slo_pts if p["x"] >= FLOOR), key=lambda p: p["y"])
    bad = [p for p in pts if not p["ok"]]
    keyframes = []
    for i, p in enumerate(bad):  # hollow one by one between 36% and 52% of the loop, worst TTFT first
        rank = sorted(bad, key=lambda q: -q["ttft90"]).index(p)
        t0 = 36 + rank * 1.6
        keyframes.append(f"@keyframes hollow{i} {{ 0% {{ fill-opacity: 1; }} {t0:.1f}% {{ fill-opacity: 1; }} {t0 + 1.2:.1f}% {{ fill-opacity: 0; }} 97% {{ fill-opacity: 0; }} 100% {{ fill-opacity: 1; }} }}")
    out = []
    w = out.append
    w('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 560" width="960" height="560" role="img" aria-labelledby="t d">')
    w(f"""<!--
Generated by scripts/anim_slo_frontier.py from data/h100/agg-dp4.points.json, agg-4x-tp1.points.json,
pd-2p1d-dtp2-bs64-run2.points.json (c64 to c1024) and pd-2p1d-dtp2-bs64-run1.points.json (c16 only).
x = tok/s per user = 1000 / ITL p90; y = output tok/s per GPU (all 4 GPUs); hollow = TTFT p90 > 2,000 ms.
TTFT-blind best at >= {FLOOR} tok/s/user: {pb['y']:,.0f} ({pb['label']}, c{pb['c']}, TTFT p90 {pb['ttft90']:,.0f} ms, SLO-ok {100 * pb['slo']:.1f}%).
SLO-respecting best: {ps['y']:,.0f} ({ps['label']}, c{ps['c']}, TTFT p90 {ps['ttft90']:,.0f} ms, SLO-ok {100 * ps['slo']:.1f}%). Overstatement {100 * over:.1f}%.
-->""")
    w('<title id="t">A TTFT-blind frontier overstates disaggregated throughput by about 50% on H100</title>')
    w(f'<desc id="d">Animated scatter of output tokens per second per GPU against tokens per second per user (1000 / ITL p90) for three layouts on 4x H100 with Qwen3-30B-A3B, prompt-heavy traffic (4,000 tokens in, 200 out), concurrency 16 to 1,024. First the usual frontier is drawn ignoring time to first token: at or above {FLOOR} tokens per second per user its best point is {pb["label"]} at concurrency {pb["c"]}, {pb["y"]:,.0f} tokens per second per GPU, with TTFT p90 {pb["ttft90"] / 1000:.1f} s and {100 * pb["slo"]:.1f}% of requests meeting the SLO. Then every point with TTFT p90 above 2 s turns hollow, and the frontier is rebuilt from the filled points: its best point is the same P/D layout at concurrency {ps["c"]}, {ps["y"]:,.0f} tokens per second per GPU, TTFT p90 {ps["ttft90"] / 1000:.1f} s, {100 * ps["slo"]:.1f}% SLO-ok. The TTFT-blind view is {100 * over:.1f}% higher.</desc>')
    w("<style>")
    w("""  .bg { fill: #ffffff; } .ink { fill: #0b0b0b; } .muted { fill: #52514e; } .axis { stroke: #8a8985; } .grid { stroke: #e4e3df; }
  .s0 { fill: #2a78d6; stroke: #2a78d6; } .s1 { fill: #eb6834; stroke: #eb6834; } .s2 { fill: #008300; stroke: #008300; }
  .pt { stroke-width: 2.2; } .bad { fill-opacity: 0; }
  .blind { fill: none; stroke: #8a8985; stroke-width: 2.5; stroke-dasharray: 7 5; }
  .slo { fill: none; stroke: #6250d6; stroke-width: 3.5; }
  .slofill { fill: #6250d6; } .bracket { stroke: #e34948; stroke-width: 2; fill: none; } .red { fill: #c62f2e; }
  .card { fill: #f4f4f2; stroke: #d6d5d0; }
  text { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif; }
  .title { font-size: 18px; font-weight: 650; } .label { font-size: 13px; } .small { font-size: 11.5px; } .bold { font-weight: 650; } .big { font-size: 22px; font-weight: 700; }
  .phase { opacity: 0; } .p3 { opacity: 1; }
  @media (prefers-color-scheme: dark) {
    .bg { fill: #0d1117; } .ink { fill: #ececea; } .muted { fill: #a8a7a3; } .axis { stroke: #6e7681; } .grid { stroke: #262c36; }
    .s0 { fill: #5a9be6; stroke: #5a9be6; } .s1 { fill: #f08a5d; stroke: #f08a5d; } .s2 { fill: #3fb950; stroke: #3fb950; }
    .blind { stroke: #a8a7a3; } .slo { stroke: #a495f0; } .slofill { fill: #a495f0; } .bracket { stroke: #ff7b72; } .red { fill: #ff7b72; }
    .card { fill: #161b22; stroke: #30363d; }
  }""")
    w(f"""  @keyframes blindIn {{ 0% {{ opacity: 0; }} 4% {{ opacity: 0; }} 12% {{ opacity: 1; }} 97% {{ opacity: 1; }} 100% {{ opacity: 0; }} }}
  @keyframes sloIn {{ 0% {{ opacity: 0; }} 60% {{ opacity: 0; }} 68% {{ opacity: 1; }} 97% {{ opacity: 1; }} 100% {{ opacity: 0; }} }}
  @keyframes gapIn {{ 0% {{ opacity: 0; }} 72% {{ opacity: 0; }} 77% {{ opacity: 1; }} 97% {{ opacity: 1; }} 100% {{ opacity: 0; }} }}
  @keyframes tagIn {{ 0% {{ opacity: 0; }} 40% {{ opacity: 0; }} 46% {{ opacity: 1; }} 97% {{ opacity: 1; }} 100% {{ opacity: 0; }} }}
  @keyframes ph1 {{ 0% {{ opacity: 1; }} 32% {{ opacity: 1; }} 34% {{ opacity: 0; }} 100% {{ opacity: 0; }} }}
  @keyframes ph2 {{ 0% {{ opacity: 0; }} 34% {{ opacity: 0; }} 36% {{ opacity: 1; }} 58% {{ opacity: 1; }} 60% {{ opacity: 0; }} 100% {{ opacity: 0; }} }}
  @keyframes ph3 {{ 0% {{ opacity: 0; }} 60% {{ opacity: 0; }} 62% {{ opacity: 1; }} 97% {{ opacity: 1; }} 100% {{ opacity: 0; }} }}
  .a-blind {{ animation: blindIn {T}s linear infinite; }} .a-slo {{ animation: sloIn {T}s linear infinite; }}
  .a-gap {{ animation: gapIn {T}s linear infinite; }} .a-tag {{ animation: tagIn {T}s linear infinite; }}
  .a-ph1 {{ animation: ph1 {T}s linear infinite; }} .a-ph2 {{ animation: ph2 {T}s linear infinite; }} .a-ph3 {{ animation: ph3 {T}s linear infinite; }}""")
    for k in keyframes:
        w("  " + k)
    w("""  @media (prefers-reduced-motion: reduce) {
    * { animation: none !important; }
    .a-ph1, .a-ph2 { opacity: 0; }
  }""")
    w("</style>")
    w('<rect class="bg" x="0" y="0" width="960" height="560" rx="10"/>')
    w('<text class="ink title" x="24" y="34">A TTFT-blind frontier credits P/D with 50% more throughput than any point that meets the SLO</text>')
    w('<text class="muted small" x="24" y="55">4x H100 SXM, Qwen3-30B-A3B, prompt-heavy (4,000 tokens in / 200 out), concurrency 16 to 1,024, closed loop. Single runs; P/D block 64 replicated.</text>')
    w('<text class="muted small" x="24" y="72">SLO: TTFT &lt;= 2 s and mean ITL &lt;= 50 ms. Hollow = TTFT p90 above 2 s. Percentiles over measured requests (warm-up excluded).</text>')
    # grid and axes
    for v in range(0, 1501, 250):
        w(f'<line class="grid" x1="{X0}" y1="{Y(v):.1f}" x2="{X1}" y2="{Y(v):.1f}" stroke-width="1"/>')
        w(f'<text class="muted small" x="{X0 - 8}" y="{Y(v) + 4:.1f}" text-anchor="end">{v:,}</text>')
    for v in range(0, 121, 20):
        w(f'<line class="axis" x1="{X(v):.1f}" y1="{Y0}" x2="{X(v):.1f}" y2="{Y0 + 5}" stroke-width="1"/>')
        w(f'<text class="muted small" x="{X(v):.1f}" y="{Y0 + 19}" text-anchor="middle">{v}</text>')
    w(f'<line class="axis" x1="{X0}" y1="{Y0}" x2="{X1}" y2="{Y0}" stroke-width="1.2"/><line class="axis" x1="{X0}" y1="{Y0}" x2="{X0}" y2="{Y1 - 6}" stroke-width="1.2"/>')
    w(f'<text class="ink small" x="{(X0 + X1) / 2:.0f}" y="{Y0 + 40}" text-anchor="middle">tok/s per user = 1000 / ITL p90 (streaming speed of the slowest tenth; ignores TTFT)</text>')
    w(f'<text class="ink small" transform="translate(30 {(Y0 + Y1) / 2:.0f}) rotate(-90)" text-anchor="middle">output tok/s per GPU</text>')
    w(f'<line class="axis" x1="{X(FLOOR):.1f}" y1="{Y0}" x2="{X(FLOOR):.1f}" y2="{Y1 - 6}" stroke-width="1" stroke-dasharray="2 3"/>')
    w(f'<text class="muted small" x="{X(FLOOR) + 5:.1f}" y="{Y0 - 8}">floor {FLOOR} tok/s/user</text>')
    # frontiers
    w(f'<path class="blind a-blind" d="{blind_d}"/>')
    w(f'<path class="slo a-slo" d="{slo_d}"/>')
    # points
    for i, p in enumerate(pts):
        bi = bad.index(p) if p in bad else 0
        w(marker(p, bi))
    # point tags (TTFT p90 of hollow P/D and agg points)
    def tag(p, txt, dx, dy, anchor="start"):
        w(f'<text class="ink small a-tag" x="{X(p["x"]) + dx:.1f}" y="{Y(p["y"]) + dy:.1f}" text-anchor="{anchor}">{txt}</text>')
    pd = {p["c"]: p for p in pts if p["label"].startswith("P/D")}
    dp4 = {p["c"]: p for p in pts if p["label"] == "agg DP4"}
    tp1 = {p["c"]: p for p in pts if p["label"] == "agg 4x TP1"}
    tag(pd[1024], f"P/D c1024: TTFT p90 {pd[1024]['ttft90'] / 1000:.1f} s", 12, -8)
    tag(pd[256], f"P/D c256: {pd[256]['ttft90'] / 1000:.1f} s", 12, 16)
    agg_bad = [p for p in bad if not p["label"].startswith("P/D")]
    lo, hi = min(p["ttft90"] for p in agg_bad), max(p["ttft90"] for p in agg_bad)
    w(f'<text class="ink small a-tag" x="{X(76):.1f}" y="{Y(1050):.1f}">hollow agg points: TTFT p90 {lo / 1000:.1f} to {hi / 1000:.1f} s</text>')
    # static labels for the two key filled points
    w(f'<text class="muted small" x="{X(ps["x"]) + 12:.1f}" y="{Y(ps["y"]) + 4:.1f}">P/D c64</text>')
    # gap bracket at the floor
    bx = X(3)
    w(f'<g class="a-gap"><path class="bracket" d="M{bx - 6:.1f},{Y(blind):.1f} H{bx:.1f} V{Y(slo):.1f} H{bx - 6:.1f}"/>'
      f'<text class="red big" x="{bx + 8:.1f}" y="{(Y(blind) + Y(slo)) / 2 + 14:.1f}">+{100 * over:.1f}%</text></g>')
    # right card
    cx = 664
    w(f'<rect class="card" x="{cx}" y="96" width="276" height="300" rx="8" stroke-width="1"/>')
    def lines(cls, x, y, rows, step=18):
        return "".join(f'<text class="{c}" x="{x}" y="{y + i * step}">{t}</text>' for i, (c, t) in enumerate(rows))
    w(f'<g class="phase a-ph1">' + lines("ink", cx + 16, 124, [
        ("ink label bold", "1. The usual frontier"),
        ("ink small", "Most output per GPU at each streaming"),
        ("ink small", "speed, TTFT ignored (dashed line)."),
        ("ink small", ""),
        ("ink small", f"At &gt;= {FLOOR} tok/s/user the best point is"),
        ("ink small bold", f"P/D c{pb['c']}: {pb['y']:,.0f} tok/s/GPU"),
        ("ink small", "It looks like a clear win for P/D."),
    ]) + "</g>")
    w(f'<g class="phase a-ph2">' + lines("ink", cx + 16, 124, [
        ("ink label bold", "2. Check TTFT p90 against 2 s"),
        ("ink small", "Points that miss it turn hollow."),
        ("ink small", ""),
        ("ink small bold", f"P/D c{pb['c']}: TTFT p90 {pb['ttft90'] / 1000:.1f} s,"),
        ("ink small bold", f"{100 * pb['slo']:.1f}% of requests meet the SLO."),
        ("ink small", "Its users stream fast only after"),
        ("ink small", "half a minute in the prefill queue."),
    ]) + "</g>")
    w(f'<g class="phase p3 a-ph3">' + lines("ink", cx + 16, 124, [
        ("ink label bold", "3. Rebuild from filled points"),
        ("ink small", "SLO-respecting frontier (solid line)."),
        ("ink small", ""),
        ("ink small bold", f"Best: P/D c{ps['c']}, {ps['y']:,.0f} tok/s/GPU"),
        ("ink small", f"TTFT p90 {ps['ttft90'] / 1000:.1f} s, {100 * ps['slo']:.1f}% SLO-ok"),
        ("ink small", ""),
        ("red small bold", f"The blind view is {100 * over:.1f}% higher."),
        ("ink small", "Rank layouts on SLO-meeting points,"),
        ("ink small", "not on the blind frontier."),
    ]) + "</g>")
    # legend
    ly = 300
    leg = [("s0", "circle", "agg DP4 (experts split 4 ways)"), ("s1", "square", "agg 4x TP1 replicas"), ("s2", "diamond", "P/D 2P(TP1):1D(TP2), block 64")]
    for i, (c, shp, txt) in enumerate(leg):
        y = ly + i * 22
        x = cx + 24
        if shp == "circle":
            w(f'<circle class="pt {c}" cx="{x}" cy="{y}" r="6"/>')
        elif shp == "square":
            w(f'<rect class="pt {c}" x="{x - 5.5}" y="{y - 5.5}" width="11" height="11"/>')
        else:
            w(f'<path class="pt {c}" d="M{x},{y - 7} L{x + 7},{y} L{x},{y + 7} L{x - 7},{y} Z"/>')
        w(f'<text class="ink small" x="{x + 14}" y="{y + 4}">{txt}</text>')
    w(f'<line class="blind" x1="{cx + 16}" y1="{ly + 66}" x2="{cx + 34}" y2="{ly + 66}"/><text class="ink small" x="{cx + 40}" y="{ly + 70}">TTFT-blind frontier</text>')
    w(f'<line class="slo" x1="{cx + 16}" y1="{ly + 86}" x2="{cx + 34}" y2="{ly + 86}"/><text class="ink small" x="{cx + 40}" y="{ly + 90}">SLO-respecting frontier</text>')
    w('<text class="muted small" x="24" y="538">Per-GPU values divide by all 4 GPUs (prefill and decode). Data: data/h100/*.points.json; every point and percentile in data/derived/TABLES.md.</text>')
    w("</svg>")
    (ROOT / "figures/anim").mkdir(parents=True, exist_ok=True)
    open(ROOT / "figures/anim/anim-slo-frontier.svg", "w").write("\n".join(out) + "\n")
    print(f"blind {blind:,.0f}, slo {slo:,.0f}, overstatement {100 * over:.1f}%")


if __name__ == "__main__":
    main()
